num = int(input("Enter a number: "))

# Convert to different data types
float_num = float(num)
string_num = str(num)

print(f"Integer: {num}")
print(f"Float: {float_num}")
print(f"String: {string_num}")

print ("Type of num:", type(num))
print ("Type of float_num:", type(float_num))
print ("Type of string_num:", type(string_num))