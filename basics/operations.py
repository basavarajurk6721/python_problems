num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number:"))

sum = num1 + num2
difference = num1 - num2
product = num1 * num2
quotient = num1 / num2
remainder = num1 % num2

# print the results
print("sum of {} and {} is: {}".format(num1, num2, sum))
print("difference of {} and {} is: {}".format(num1, num2, difference))
print("product of {} and {} is: {}".format(num1, num2, product))
print("quotient of {} and {} is: {}".format(num1, num2, quotient))
print("remainder of {} and {} is: {}".format(num1, num2, remainder))